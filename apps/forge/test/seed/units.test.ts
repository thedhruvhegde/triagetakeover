/** Pure pieces of the demo seed: ARI, engine labels, item markers, ADF text, dates, state parsing. */
import { describe, expect, it } from "vitest";
import fc from "fast-check";
import { DEFAULT_SEED, PROFILE_ID, generateEventFiles, planFleet } from "@tt/seedgen";
import { TT_THUMBS_TARGET_BYTES, serializedSize } from "@tt/engine";
import { adjustedRandIndex, engineLabelOf } from "../../src/services/seed/report.js";
import { adfToText, itemMarker, parseItemMarker, thumbsFromFrames } from "../../src/services/seed/generate.js";
import { SEED_STEPS, mondayOnOrBefore, parseJobRecord, parseManifest, positionOf } from "../../src/services/seed/state.js";
import { CallCounter, counted } from "../../src/services/seed/counting.js";
import { backoffSeconds } from "../../src/consumers/seed-job.js";
import type { EventRow } from "../../src/ports/entities.js";

const row = (over: Partial<EventRow>): EventRow => ({
  issueKey: "TTDEMO-1", projectKey: "TTDEMO", bucket: "lane-loss|cam-B", type: "lane-loss", variant: "cam-B", build: "4.12.0", occurredAt: 0,
  status: "unassigned", clusterId: "", proposalId: "", nnDist: -1, chipsMask: 0, features: { F1: 0, F2: 0, F3: 0, F4: 0, F5: 0, F6: 0, F7: 0, F8: 0, F9: 0, F10: 0 }, engine: "1.0.0", synthetic: true, indexedAt: 0, ...over,
});

describe("adjustedRandIndex", () => {
  it("matches known values", () => {
    expect(adjustedRandIndex(["a", "a", "b", "b"], ["x", "x", "y", "y"])).toBe(1);
    expect(adjustedRandIndex(["0", "0", "1", "1"], ["0", "0", "1", "2"])).toBeCloseTo(0.5714285714, 9);
    expect(adjustedRandIndex(["a", "b", "c", "d"], ["x", "x", "x", "x"])).toBe(0);
    expect(adjustedRandIndex(["a"], ["b"])).toBe(1);
    expect(() => adjustedRandIndex(["a"], [])).toThrow(RangeError);
  });

  it("is symmetric, at most 1 and invariant to relabelling", () => {
    const labels = fc.array(fc.constantFrom("p", "q", "r", "s"), { minLength: 2, maxLength: 30 });
    fc.assert(
      fc.property(labels, fc.array(fc.constantFrom("u", "v", "w"), { minLength: 30, maxLength: 30 }), (a, bb) => {
        const b = bb.slice(0, a.length);
        const ab = adjustedRandIndex(a, b);
        expect(ab).toBeCloseTo(adjustedRandIndex(b, a), 12);
        expect(ab).toBeLessThanOrEqual(1 + 1e-12);
        expect(adjustedRandIndex(a, a.map((x) => `${x}!`))).toBeCloseTo(1, 12);
      }),
      { numRuns: 200 },
    );
  });
});

describe("engineLabelOf", () => {
  it("maps rows to the engine's partition", () => {
    expect(engineLabelOf("1", row({ status: "accepted", clusterId: "9" }))).toBe("cluster:9");
    expect(engineLabelOf("1", row({ status: "proposed", proposalId: "c:9" }))).toBe("cluster:9");
    expect(engineLabelOf("1", row({ status: "proposed", proposalId: "p:TTDEMO-4" }))).toBe("group:TTDEMO-4");
    expect(engineLabelOf("1", row({ status: "novel", proposalId: "n:9" }))).toBe("single:1");
    expect(engineLabelOf("1", row({ status: "novel", proposalId: "f:" }))).toBe("single:1");
    expect(engineLabelOf("1", undefined)).toBe("single:1");
  });
});

describe("item markers and descriptions", () => {
  it("round-trips the item marker and finds it inside seedgen's banner", () => {
    expect(parseItemMarker(`x ${itemMarker(42, "CL-E-007")}. y`)).toEqual({ seed: 42, itemId: "CL-E-007" });
    expect(parseItemMarker("Generated by Takeover Triage. Not real.")).toBeNull();
    expect(parseItemMarker(undefined)).toBeNull();
    const plan = planFleet({ seed: DEFAULT_SEED, anchorDate: "2026-11-16", profile: PROFILE_ID, frames: "fast" });
    const e = plan.events[0];
    if (e === undefined) throw new Error("no events");
    const text = adfToText(e.descriptionAdf);
    expect(parseItemMarker(text)).toEqual({ seed: DEFAULT_SEED, itemId: e.eventId });
    expect(text).toMatch(/^Synthetic demo data\./);
    expect(text).toContain(`Driver note: ${e.note}`);
    expect(text).toMatch(/Vehicle: SYN test vehicle 0\d/);
    const s = plan.scenarios[0];
    expect(parseItemMarker(adfToText(s?.descriptionAdf ?? { content: [] }))?.itemId).toBe(s?.id);
  });

  it("thumbnails fit the 12 KB tt.thumbs target", () => {
    const cfg = { seed: DEFAULT_SEED, anchorDate: "2026-11-16", profile: PROFILE_ID, frames: "fast" } as const;
    const plan = planFleet(cfg);
    const e = plan.events.find((x) => x.frameCount >= 2) ?? plan.events[0];
    const files = generateEventFiles(cfg, e?.eventId ?? "", plan);
    const t = thumbsFromFrames(files.frames.map((f) => f.bytes));
    expect(t?.frames.length).toBeGreaterThanOrEqual(1);
    const size = t === undefined ? null : serializedSize(t);
    expect(size?.ok && size.value).toBeLessThanOrEqual(TT_THUMBS_TARGET_BYTES);
    expect(Math.max(...(t?.frames ?? []).map((f) => Math.max(f.w, f.h)))).toBeLessThanOrEqual(128);
  });
});

describe("state helpers", () => {
  it("mondayOnOrBefore", () => {
    expect(mondayOnOrBefore("2026-11-20T09:00:00.000Z")).toBe("2026-11-16");
    expect(mondayOnOrBefore("2026-11-16T00:00:00.000Z")).toBe("2026-11-16");
    expect(mondayOnOrBefore("2026-11-22T23:59:59.000Z")).toBe("2026-11-16");
    expect(mondayOnOrBefore("2026-11-23T00:00:01.000Z")).toBe("2026-11-23");
    expect(mondayOnOrBefore("1970-01-01T00:00:00.000Z")).toBe("1969-12-29");
  });

  it("chain positions are totally ordered by step then cursor", () => {
    for (let i = 1; i < SEED_STEPS.length; i++) {
      const a = SEED_STEPS[i - 1];
      const b = SEED_STEPS[i];
      if (a === undefined || b === undefined) continue;
      expect(positionOf(a, 999_999)).toBeLessThan(positionOf(b, 0));
    }
    expect(positionOf("history", 3)).toBeLessThan(positionOf("history", 4));
  });

  it("rejects malformed stored state", () => {
    expect(parseManifest(undefined)).toBeNull();
    expect(parseManifest({ v: 2 })).toBeNull();
    expect(parseManifest({ v: 1, projectKey: "X", seed: -1, jobId: "j", anchorDate: "2026-11-16", by: "a" })).toBeNull();
    const m = parseManifest({ v: 1, projectKey: "X", seed: 1, jobId: "j", anchorDate: "2026-11-16", by: "a", items: { a: { id: "1", key: "X-1" }, b: { id: 2 } }, pending: ["E-001", 3], clusterPlan: "bad" });
    expect(m?.items).toEqual({ a: { id: "1", key: "X-1" } });
    expect(m?.pending).toEqual(["E-001"]);
    expect(m?.clusterPlan).toBeNull();
    expect(parseJobRecord({ v: 1, jobId: "j", projectKey: "X", seed: 1, step: "bogus", cursor: 0 })).toBeNull();
    expect(parseJobRecord({ v: 1, jobId: "j", projectKey: "X", seed: 1, step: "history", cursor: 2, state: "weird" })?.state).toBe("failed");
  });

  it("back-off honours Retry-After and doubles otherwise, within the queue's 900 s", () => {
    expect(backoffSeconds({ kind: "rate-limited", message: "", retryAfterSeconds: 7 }, 3)).toBe(7);
    expect(backoffSeconds({ kind: "unavailable", message: "" }, 1)).toBe(5);
    expect(backoffSeconds({ kind: "unavailable", message: "" }, 3)).toBe(20);
    expect(backoffSeconds({ kind: "unavailable", message: "" }, 30)).toBe(900);
  });

  it("counts calls per port method", async () => {
    const c = new CallCounter();
    const t = counted({ async a() { return 1; }, b: 2 }, "x", c);
    await t.a();
    await t.a();
    expect(t.b).toBe(2);
    expect(c.snapshot()).toEqual({ "x.a": 2 });
    expect(c.total("x.")).toBe(2);
  });
});
