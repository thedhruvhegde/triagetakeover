/**
 * The admin-only seed report (ARCHITECTURE §9 step 6, SEED_DATA §15.1 S10).
 *
 * Ground truth is regenerated on demand from `(seed, anchorDate, profile)` with seedgen's
 * pure `buildTruth`; it is used here only to score what the engine did and is never written
 * to Jira, to the index or to anything the engine or the board reads (SEED_DATA §14.1). The
 * stored report keeps aggregates (ARI, counts) plus the disclosed planted-event list.
 */
import { DEFAULT_SEED, GENERATOR_VERSION, PROFILE_ID, buildTruth, paramsHash, type GroundTruth, type SeedConfig } from "@tt/seedgen";
import type { EventRow } from "../../ports/entities";
import { decodeProposal, type Keyed } from "../index-store";
import type { SeedJobRecord, SeedManifest } from "./state";

/** C(n, 2). */
const pairs = (n: number): number => (n * (n - 1)) / 2;

/**
 * Adjusted Rand index between two labelings of the same items (Hubert & Arabie 1985).
 * 1 = identical partitions, ≈ 0 = chance agreement. Two trivial partitions that agree give 1.
 */
export function adjustedRandIndex(a: readonly string[], b: readonly string[]): number {
  if (a.length !== b.length) throw new RangeError("labelings must have the same length");
  const n = a.length;
  if (n < 2) return 1;
  const cells = new Map<string, number>();
  const rows = new Map<string, number>();
  const cols = new Map<string, number>();
  for (let i = 0; i < n; i++) {
    const x = a[i] ?? "";
    const y = b[i] ?? "";
    cells.set(`${x}\u0000${y}`, (cells.get(`${x}\u0000${y}`) ?? 0) + 1);
    rows.set(x, (rows.get(x) ?? 0) + 1);
    cols.set(y, (cols.get(y) ?? 0) + 1);
  }
  let sumCells = 0;
  for (const c of cells.values()) sumCells += pairs(c);
  let sumRows = 0;
  for (const c of rows.values()) sumRows += pairs(c);
  let sumCols = 0;
  for (const c of cols.values()) sumCols += pairs(c);
  const expected = (sumRows * sumCols) / pairs(n);
  const max = (sumRows + sumCols) / 2;
  if (max === expected) return sumCells === max ? 1 : 0;
  return (sumCells - expected) / (max - expected);
}

/**
 * The engine's partition of an event, from its index row: accepted cluster, kNN-suggested
 * cluster, HAC proposal group, or a singleton (novel, first-of-kind, unassigned, missing).
 */
export function engineLabelOf(issueId: string, row: EventRow | undefined): string {
  if (row === undefined) return `single:${issueId}`;
  if (row.status === "accepted" && row.clusterId !== "") return `cluster:${row.clusterId}`;
  const p = decodeProposal(row.proposalId);
  if (p.kind === "suggest" && p.clusterId !== "") return `cluster:${p.clusterId}`;
  if (p.kind === "group") return `group:${p.groupId}`;
  return `single:${issueId}`;
}

export interface SeedReport {
  readonly v: 1;
  readonly projectKey: string;
  readonly seed: number;
  readonly anchorDate: string;
  readonly frames: "full" | "fast";
  readonly profile: string;
  readonly generator: string;
  readonly paramsHash: string;
  readonly defaultSeed: number;
  readonly isDefaultSeed: boolean;
  readonly defaultSeedRule: string;
  readonly counts: Readonly<Record<string, number>>;
  readonly planted: readonly { readonly role: string; readonly eventId: string; readonly issueKey: string | null }[];
  readonly accuracy: {
    /** ARI of the engine's partition (all events incl. boundary; novel = singleton) vs the generator's latent clusters. */
    readonly ariAll: number | null;
    /** The same without the deliberately ambiguous boundary events. */
    readonly ariExcludingBoundary: number | null;
    /** ARI of the history clustering the seed accepted (the engine's HAC proposal, S6) vs latent clusters. */
    readonly ariHistoryProposal: number | null;
    readonly events: number;
    readonly boundaryEvents: number;
    readonly latentClusters: number;
    readonly engineGroups: number;
    readonly note: string;
  };
  readonly attachments: SeedJobRecord["attachments"];
  readonly failedEvents: readonly string[];
  readonly timings: { readonly totalMs: number; readonly steps: Readonly<Record<string, { readonly runs: number; readonly ms: number }>> };
  readonly calls: Readonly<Record<string, Readonly<Record<string, number>>>>;
  readonly honesty: readonly string[];
}

export const DEFAULT_SEED_RULE =
  "The default seed is the smallest seed ≥ 2026 that, with the frozen parameters, exercises every demo state (SEED_DATA §13.1). Try any seed: the mechanisms are the same, but verdicts follow the generated data and can be inconclusive. The share of random seeds that exercise every state has not been measured in this build.";

export const REPORT_HONESTY = [
  "All data in this project is SYNTHETIC: generated by the Takeover Triage demo seed, not real vehicle, fleet or driver data.",
  "Rates, archetypes and render conditions were chosen by the developer. The accuracy numbers measure the engine against this generator, not against real fleets.",
  "The ground truth used for these numbers is regenerated from the seed for this report only; it is never written to Jira or read by the engine.",
  "Historical links were made from the engine's own proposal over the historical events, not from the ground truth.",
] as const;

const round = (x: number | null): number | null => (x === null || !Number.isFinite(x) ? null : Math.round(x * 10_000) / 10_000);

export function buildSeedReport(input: {
  readonly manifest: SeedManifest;
  readonly job: SeedJobRecord;
  readonly rows: readonly Keyed<EventRow>[];
  readonly truth?: GroundTruth;
}): SeedReport {
  const { manifest: m, job } = input;
  const cfg: SeedConfig = { seed: m.seed, anchorDate: m.anchorDate, profile: PROFILE_ID, frames: m.frames };
  const truth = input.truth ?? buildTruth(cfg);
  const rowById = new Map(input.rows.map((r) => [r.key, r.value]));

  const scored = truth.events.filter((e) => m.items[e.eventId] !== undefined);
  const latent = scored.map((e) => e.latent);
  const engine = scored.map((e) => {
    const id = m.items[e.eventId]?.id ?? e.eventId;
    return engineLabelOf(id, rowById.get(id));
  });
  const clean = scored.map((e, i) => ({ e, i })).filter(({ e }) => e.boundary.length === 0);
  const ariAll = scored.length >= 2 ? adjustedRandIndex(engine, latent) : null;
  const ariClean = clean.length >= 2 ? adjustedRandIndex(clean.map(({ i }) => engine[i] ?? ""), clean.map(({ e }) => e.latent)) : null;

  const history = truth.events.filter((e) => !e.monday && m.items[e.eventId] !== undefined);
  const groupOf = new Map<string, string>();
  for (const c of m.clusterPlan ?? []) for (const id of c.members) groupOf.set(id, c.itemId);
  const ariHistory = history.length >= 2 ? adjustedRandIndex(history.map((e) => groupOf.get(e.eventId) ?? `single:${e.eventId}`), history.map((e) => e.latent)) : null;

  const steps: Record<string, { runs: number; ms: number }> = {};
  const calls: Record<string, Record<string, number>> = {};
  let totalMs = 0;
  for (const [name, s] of Object.entries(job.stats)) {
    steps[name] = { runs: s.runs, ms: Math.round(s.ms) };
    calls[name] = { ...s.calls };
    totalMs += s.ms;
  }

  return {
    v: 1,
    projectKey: m.projectKey,
    seed: m.seed,
    anchorDate: m.anchorDate,
    frames: m.frames,
    profile: PROFILE_ID,
    generator: GENERATOR_VERSION,
    paramsHash: paramsHash(),
    defaultSeed: DEFAULT_SEED,
    isDefaultSeed: m.seed === DEFAULT_SEED,
    defaultSeedRule: DEFAULT_SEED_RULE,
    counts: { ...job.counts },
    planted: Object.entries(truth.roles)
      .filter((x): x is [string, string] => typeof x[1] === "string")
      .map(([role, eventId]) => ({ role, eventId, issueKey: m.items[eventId]?.key ?? null }))
      .sort((a, b) => (a.role < b.role ? -1 : a.role > b.role ? 1 : 0)),
    accuracy: {
      ariAll: round(ariAll),
      ariExcludingBoundary: round(ariClean),
      ariHistoryProposal: round(ariHistory),
      events: scored.length,
      boundaryEvents: scored.length - clean.length,
      latentClusters: new Set(latent).size,
      engineGroups: new Set(engine).size,
      note: "Adjusted Rand index between the engine's grouping (accepted cluster, suggested cluster or proposed group; novel and unmatched events count as singletons) and the generator's latent clusters, on this seed only.",
    },
    attachments: job.attachments,
    failedEvents: [...m.failedEvents],
    timings: { totalMs: Math.round(totalMs), steps },
    calls,
    honesty: [...REPORT_HONESTY],
  };
}
