/**
 * Driver notes and issue templates (SEED_DATA §10). Notes are drawn 50/50 from a pool shared
 * by every cluster and from the cluster's own pool, so text alone cannot separate clusters.
 * No latent id, archetype name or expected verdict ever appears in Jira-bound text (§2.4).
 */
import type { Rng } from "../rng/index.js";
import type { AdfDoc, AdfNode, DriveSessionRecord, LatentId, VehicleRecord } from "../types.js";

export const SHARED_NOTES: readonly string[] = [
  "car drifted left, took over",
  "took over, didn't like it",
  "felt unsafe, took control",
  "system gave up, I took over",
  "it braked hard, I took over",
];

export const CLUSTER_NOTES: Readonly<Record<LatentId, readonly string[]>> = {
  "LC-A": ["drifted towards the line, I took over", "LKA let go, took over", "lines disappeared in the sun, took over", "lost the lane, grabbed the wheel"],
  "LC-B": ["braked too late behind the car in front", "had to stomp on the brake", "closing too fast, I braked"],
  "LC-C": ["steering went light near the exit, grabbed the wheel", "ran wide on the curve", "didn't hold the bend, took over"],
  "LC-D": ["slammed the brakes for nothing", "random hard brake under the bridge", "phantom brake, overrode it"],
  "NOVEL-1": ["lines ended at the road works, swerved, took over"],
};

/** Planted notes (§7.2). */
export const NOTE_DRIFTED_LEFT = "car drifted left, took over";
export const NOTE_BRAKED_HARD = "it braked hard, I took over";
export const NOTE_STEERING_LIGHT = "steering went light near the exit, grabbed the wheel";

/** Context suffixes consistent with the session tags. */
function suffixesFor(s: DriveSessionRecord): string[] {
  const out: string[] = [];
  if (s.route === "highway") out.push("on the highway loop");
  if (s.route === "rural") out.push("on the rural loop");
  if (s.route === "urban") out.push("in town");
  if (s.light === "low-sun") out.push(s.startEpoch % 86400 < 12 * 3600 ? "early morning" : "around 5pm");
  if (s.light === "night") out.push("after dark");
  if (s.weather === "rain") out.push("wet road");
  return out;
}

/** Draws a driver note: shared vs own pool 50/50 (NOVEL-1 own only), optional suffix 40 %. */
export function drawNote(rng: Rng, latent: LatentId, session: DriveSessionRecord): string {
  const own = CLUSTER_NOTES[latent];
  const pool = latent === "NOVEL-1" || rng.chance(0.5) ? own : SHARED_NOTES;
  const base = rng.pick(pool);
  if (!rng.chance(0.4)) return base;
  return `${base} ${rng.pick(suffixesFor(session))}`;
}

/** `[SYNTHETIC] Takeover: <note> (<vehicleLabel>, <build>)`, truncated to 120 characters. */
export function eventSummary(note: string, vehicle: VehicleRecord, build: string): string {
  const s = `[SYNTHETIC] Takeover: ${note} (${vehicle.label}, ${build})`;
  return s.length <= 120 ? s : `${s.slice(0, 119)}…`;
}

export const EVENT_LABELS: readonly string[] = ["tt-synthetic", "tt-takeover"];

const text = (t: string, strong = false): AdfNode => (strong ? { type: "text", text: t, marks: [{ type: "strong" }] } : { type: "text", text: t });
const para = (...content: AdfNode[]): AdfNode => ({ type: "paragraph", content });
const cell = (type: "tableHeader" | "tableCell", t: string): AdfNode => ({ type, content: [para(text(t))] });

/** Synthetic-data info panel used on every seeded issue. */
export function syntheticPanel(seed: number, itemId: string, extra?: string): AdfNode {
  const content: AdfNode[] = [
    text("Synthetic demo data.", true),
    text(` Generated by Takeover Triage (seed ${seed}, ${itemId}). Not real vehicle, fleet or driver data. Created by Takeover Triage demo seed.`),
  ];
  if (extra !== undefined) content.push(text(` ${extra}`));
  return { type: "panel", attrs: { panelType: "info" }, content: [para(...content)] };
}

export interface EventDescriptionInput {
  readonly seed: number;
  readonly eventId: string;
  readonly note: string;
  readonly vehicle: VehicleRecord;
  readonly session: DriveSessionRecord;
  readonly occurredAt: string;
}

/** Event description ADF (§10.2): banner, note, metadata table, attachments line. */
export function eventDescription(e: EventDescriptionInput): AdfDoc {
  const rows: [string, string][] = [
    ["Vehicle", e.vehicle.label],
    ["Build", e.session.build],
    ["Drive session", e.session.label],
    ["Occurred at (synthetic)", e.occurredAt],
    ["ODD tags", e.session.odd.join(", ")],
  ];
  return {
    type: "doc",
    version: 1,
    content: [
      syntheticPanel(e.seed, e.eventId),
      para(text(`Driver note: ${e.note}`)),
      {
        type: "table",
        content: rows.map(([k, v]) => ({ type: "tableRow", content: [cell("tableHeader", k), cell("tableCell", v)] })),
      },
      para(text("Raw files: see attachments (telemetry CSV, dashcam stills, all synthetic).")),
    ],
  };
}

/** Plain ADF document with the synthetic banner and one paragraph. */
export function simpleDescription(seed: number, itemId: string, body: string): AdfDoc {
  return { type: "doc", version: 1, content: [syntheticPanel(seed, itemId), para(text(body))] };
}
