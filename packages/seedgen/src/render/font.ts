export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Horizontal advance per character, in font pixels (glyph + 1 column gap). */
export const GLYPH_ADVANCE = 6;

/** Rows of the glyph for `ch` (unknown characters render as blank). */
export function glyphRows(ch: string): readonly number[] {
  return GLYPHS[ch.toUpperCase()] ?? (GLYPHS[" "] as readonly number[]);
}

/** Width in pixels of `text` at integer `scale`. */
export function textWidth(text: string, scale: number): number {
  return text.length === 0 ? 0 : (text.length * GLYPH_ADVANCE - 1) * scale;
}

/** Calls `plot(x, y)` for every lit pixel of `text` drawn at (x0, y0) with integer `scale`. */
export function forEachTextPixel(text: string, x0: number, y0: number, scale: number, plot: (x: number, y: number) => void): void {
  for (let i = 0; i < text.length; i++) {
    const rows = glyphRows(text.charAt(i));
    const gx = x0 + i * GLYPH_ADVANCE * scale;
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r] ?? 0;
      for (let c = 0; c < GLYPH_W; c++) {
        if ((bits & (1 << (GLYPH_W - 1 - c))) === 0) continue;
        for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) plot(gx + c * scale + dx, y0 + r * scale + dy);
      }
    }
  }
}
